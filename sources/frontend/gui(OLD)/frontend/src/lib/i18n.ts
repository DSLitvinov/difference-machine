export type TranslationKey = keyof typeof translations.en;

export function translate(language: GuiLanguage, key: TranslationKey, params?: Record<string, string | number>): string {
  let text: string = translations[language][key] ?? translations.en[key] ?? key;
  if (!params) return text;
  for (const [name, value] of Object.entries(params)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function useT(): (key: TranslationKey, params?: Record<string, string | number>) => string {
  const language = useAppStore((s) => s.language);
  return useCallback((key, params) => translate(language, key, params), [language]);
}
